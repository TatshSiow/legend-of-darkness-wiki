import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE});
const page=await browser.newPage({viewport:{width:1668,height:1020}});
await page.goto((process.env.BASE_URL||'http://127.0.0.1:5174')+'/home/');await page.waitForLoadState('networkidle');
assert.equal(await page.locator('.cards .card').count(),18);
assert(await page.locator('.cards .card').evaluateAll(nodes=>nodes.every(n=>n.getBoundingClientRect().height<110)));
assert.equal(await page.locator('.cards .card img').evaluateAll(nodes=>nodes.filter(n=>!n.complete||!n.naturalWidth).length),0);
await page.screenshot({path:'artifacts/home-compact.png',fullPage:true});
await page.goto((process.env.BASE_URL||'http://127.0.0.1:5174')+'/data/trial/');await page.waitForLoadState('networkidle');
assert.equal(await page.locator('.trial-rewards tbody tr').count(),91);
assert.equal(await page.locator('.trial-rewards tbody td:nth-child(2) .reward-threshold').count(),30);
assert.equal(await page.locator('.trial-rewards tbody td:nth-child(3) .reward-threshold').count(),61);
assert.equal(await page.locator('.trial-rewards tbody td:nth-child(4) .reward-threshold').count(),91);
for(const column of [2,3,4])assert.equal(await page.locator(`.trial-rewards tbody tr:first-child td:nth-child(${column}) strong`).innerText(),'60%');
await page.locator('#trial-score').fill('49');
await page.waitForFunction(()=>document.querySelectorAll('.reward-candidates').length===0);
await page.locator('#trial-score').fill('50');
await page.waitForFunction(()=>document.querySelectorAll('.reward-candidates').length===1);
assert.equal(await page.locator('.trial-rewards .reward-threshold strong').allTextContents().then(values=>values.join(',')),'60%,60%,60%');
await page.locator('#trial-score').fill('');
await page.waitForFunction(()=>document.querySelectorAll('.reward-candidates').length===91);
assert.equal(await page.locator('.trial-rewards .stack-count').count(),await page.locator('.trial-rewards .entry-identity').count());
await page.screenshot({path:'artifacts/trial-matrix.png',fullPage:true});
await page.setViewportSize({width:390,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'artifacts/trial-matrix-mobile.png',fullPage:true});
await page.goto((process.env.BASE_URL||'http://127.0.0.1:5174')+'/home/');assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await page.screenshot({path:'artifacts/home-compact-mobile.png',fullPage:true});
await browser.close();console.log('18 compact cards, valid art, 30/61/91 difficulty cells, image counts and mobile overflow passed');
